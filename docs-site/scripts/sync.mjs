// Copies the documentation from docs/ into src/content/docs/, the folder
// Starlight reads. The copy is not committed; it is made again before every
// build, so a page removed from docs/ disappears from the site.
//
// - Pages written for the site (docs/index.mdx, docs/<group>/, docs/ja/) are
//   copied as they are, with an edit link to their file in docs/.
// - The older files listed in pages.mjs (LEGACY) get front matter: the title
//   from their first heading, the description and the sidebar order.
// - Links are written as relative paths to files in the repository, so they
//   work on GitHub too. Here they become site URLs (a page of the site) or
//   GitHub URLs (any other file). A link to a file that does not exist fails
//   the sync.

import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, posix, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { BASE, GROUPS, LEGACY } from '../pages.mjs';

const site = join(dirname(fileURLToPath(import.meta.url)), '..');
const repo = join(site, '..');
const out = join(site, 'src', 'content', 'docs');
const GITHUB = 'https://github.com/geolonia/pointsman';
/** The engine version, added to the generated reference pages here, at build time, not in their committed files. */
const ENGINE_VERSION = JSON.parse(readFileSync(join(repo, 'package.json'), 'utf8')).version;
const GENERATED = '<!-- Generated by scripts/docs-reference.mjs.';
const versionNote = (ja) => ja
  ? `このページは、エンジンのバージョン ${ENGINE_VERSION} のコードから生成しています。リリースとリリースの間は \`main\` のコードを表示するため、次のバージョンの変更がすでに入っていることがあります。`
  : `This page is generated from the code of engine version ${ENGINE_VERSION}. Between releases, the site shows the code on \`main\`, which may already have changes for the next version.`;

/** Markdown files under a folder, as repository paths. */
function walk(dir) {
  if (!existsSync(join(repo, dir))) return [];
  return readdirSync(join(repo, dir), { withFileTypes: true }).flatMap((e) => {
    const path = posix.join(dir, e.name);
    if (e.isDirectory()) return walk(path);
    return /\.mdx?$/.test(e.name) ? [path] : [];
  });
}

/** The site pages written for the site: repository path → slug (with "ja/" for Japanese). */
function sitePages() {
  const pages = new Map();
  for (const prefix of ['docs/', 'docs/ja/']) {
    const files = [
      ...['index.md', 'index.mdx'].map((f) => prefix + f).filter((f) => existsSync(join(repo, f))),
      ...GROUPS.flatMap((g) => walk(prefix + g.dir)),
    ];
    for (const file of files) pages.set(file, file.slice('docs/'.length).replace(/\.mdx?$/, '').replace(/(^|\/)index$/, ''));
  }
  return pages;
}

const pages = sitePages();
for (const [file, { slug }] of Object.entries(LEGACY)) {
  if (!existsSync(join(repo, file))) throw new Error(`pages.mjs: ${file} does not exist`);
  pages.set(file, slug);
}
if (new Set(pages.values()).size !== pages.size) throw new Error('two files in docs/ have the same slug (see pages.mjs)');
// Every Markdown file in docs/ is on the site, so none is forgotten.
const unplaced = walk('docs').filter((f) => !pages.has(f));
if (unplaced.length) throw new Error(`not on the site: ${unplaced.join(', ')}. Put each in a group folder (docs/<group>/, docs/ja/<group>/) or in LEGACY in docs-site/pages.mjs`);

/** The site URL or GitHub URL for a relative link from `from` (a repository path), or null to leave it. */
function rewrite(target, from, ja) {
  if (/^([a-z][a-z0-9+.-]*:|#|\/)/i.test(target)) return null;
  const [path, anchor] = target.split('#');
  const file = posix.normalize(posix.join(posix.dirname(from), decodeURIComponent(path)));
  if (file.startsWith('../')) throw new Error(`${from}: link "${target}" leaves the repository`);
  const hash = anchor === undefined ? '' : `#${anchor}`;
  if (pages.has(file)) {
    const slug = pages.get(file);
    // A Japanese page links to the Japanese version, which falls back to English.
    const isJa = slug === 'ja' || slug.startsWith('ja/');
    const local = ja && !isJa ? (slug === '' ? 'ja' : `ja/${slug}`) : slug;
    return `${BASE}${local}${local ? '/' : ''}${hash}`;
  }
  const full = join(repo, file.replace(/\/$/, ''));
  if (!existsSync(full)) throw new Error(`${from}: link "${target}" points at ${file}, which does not exist`);
  return `${GITHUB}/${statSync(full).isDirectory() ? 'tree' : 'blob'}/main/${encodeURI(file.replace(/\/$/, ''))}${hash}`;
}

/** Rewrites the links of a Markdown text, outside code. */
function rewriteLinks(text, from, ja) {
  // The open code fence ("```" or "~~~", three or more); it closes with the same character, at least as long.
  let fence = null;
  return text.split('\n').map((line) => {
    const f = /^\s*(`{3,}|~{3,})/.exec(line)?.[1];
    if (fence === null && f) { fence = f; return line; }
    if (fence !== null) {
      if (f && f[0] === fence[0] && f.length >= fence.length && line.trim() === f) fence = null;
      return line;
    }
    // Inline code stays as it is: split it out, rewrite the rest.
    return line.split(/(`[^`]*`)/).map((part, i) => {
      if (i % 2 === 1) return part;
      return part
        .replace(/\]\(([^)\s]+)((?:\s+"[^"]*")?)\)/g, (m, t, title) => {
          const url = rewrite(t, from, ja);
          return url === null ? m : `](${url}${title})`;
        })
        .replace(/^(\[[^\]]+\]:\s+)(\S+)/, (m, def, t) => {
          const url = rewrite(t, from, ja);
          return url === null ? m : def + url;
        })
        .replace(/(<a\s[^>]*href=")([^"]+)(")/g, (m, a, t, b) => {
          const url = rewrite(t, from, ja);
          return url === null ? m : a + url + b;
        });
    }).join('');
  }).join('\n');
}

const yaml = (value) => JSON.stringify(value);

function write(slug, file, text) {
  const ext = file.endsWith('.mdx') ? '.mdx' : '.md';
  const dest = join(out, (slug === '' ? 'index' : slug === 'ja' ? 'ja/index' : slug) + ext);
  mkdirSync(dirname(dest), { recursive: true });
  writeFileSync(dest, text);
}

rmSync(out, { recursive: true, force: true });

for (const [file, slug] of pages) {
  const ja = file.startsWith('docs/ja/');
  const source = readFileSync(join(repo, file), 'utf8');
  const legacy = LEGACY[file];
  if (legacy) {
    // The title is the first line, when it is a "# " heading.
    const m = /^\s*# (.+)\n+/.exec(source);
    if (!m && !legacy.title) throw new Error(`${file}: no "# " heading for the title`);
    const title = legacy.title ?? m[1].trim();
    const body = m ? source.slice(0, m.index) + source.slice(m.index + m[0].length) : source;
    const front = [
      '---',
      `title: ${yaml(title)}`,
      `description: ${yaml(legacy.description)}`,
      `sidebar: { order: ${legacy.order} }`,
      `editUrl: ${yaml(`${GITHUB}/edit/main/${file}`)}`,
      '---',
      '',
    ].join('\n');
    write(slug, file, front + rewriteLinks(body, file, false));
    continue;
  }
  const fm = /^---\n([\s\S]*?)\n---\n/.exec(source);
  if (!fm) throw new Error(`${file}: front matter with a title is missing`);
  const head = /^editUrl:/m.test(fm[1]) ? fm[1] : `${fm[1]}\neditUrl: ${yaml(`${GITHUB}/edit/main/${file}`)}`;
  let body = rewriteLinks(source.slice(fm[0].length), file, ja);
  if (body.includes(GENERATED)) body = body.replace(/^(<!-- Generated by [^\n]*-->\n)/m, `$1\n${versionNote(ja)}\n`);
  write(slug, file, `---\n${head}\n---\n${body}`);
}

console.log(`docs: ${pages.size} pages synced to ${relative(repo, out)}`);
