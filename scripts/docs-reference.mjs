// Writes the generated reference pages of the documentation site, in English
// and Japanese, from the code:
//
// - docs/reference/fact-types.md: fact types and their fields, from the
//   module definitions (packages/*, scripts/lib/modules.mjs) and the shared
//   capabilities (@pointsman/module-api);
// - docs/reference/connectors.md: connectors, where they run, their actions
//   and settings, from the same definitions;
// - docs/reference/http-api.md: the HTTP API, from openapi.yaml;
// - docs/reference/mcp-tools.md: the MCP tools, from src/mcp-tools.ts.
//
// `--check` writes nothing and fails when a page is out of date, so CI
// catches a change to the code without the pages. Descriptions that come
// from the code are in English on both language versions.

import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { parse } from 'yaml';
import { z } from 'zod';
import { CAPABILITIES } from '@pointsman/module-api';
import { CATALOG, loadDefinitions } from './lib/modules.mjs';
import { CORE_REASONS } from '../src/modules/registry.ts';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const check = process.argv.includes('--check');

// ---------------------------------------------------------------- helpers

/** A table cell: one line, pipes escaped. */
const cell = (value) => String(value ?? '').replace(/\s*\n\s*/g, ' ').replaceAll('|', '\\|').trim() || ' ';
const table = (head, rows) => [
  `| ${head.map(cell).join(' | ')} |`,
  `| ${head.map(() => '---').join(' | ')} |`,
  ...rows.map((r) => `| ${r.map(cell).join(' | ')} |`),
].join('\n');
const code = (s) => `\`${s}\``;
const list = (items) => items.map(code).join(', ');
/** A link from a generated page (docs/reference/ or docs/ja/reference/) to a path under docs/. */
const rel = (lang, path) => (lang === 'en' ? '../' : '../../') + path;
/** A definition's one-line description ("type: what it is.") as a sentence. */
const sentence = (d) => {
  const text = d.replace(/^[a-z0-9_/-]+:\s*/, '').trim();
  return text.charAt(0).toUpperCase() + text.slice(1);
};

function page(lang, { title, description, intro, order }, sections) {
  const source = 'scripts/docs-reference.mjs';
  return [
    '---',
    `title: ${JSON.stringify(title)}`,
    `description: ${JSON.stringify(description)}`,
    `sidebar: { order: ${order} }`,
    'editUrl: false',
    '---',
    '',
    `<!-- Generated by ${source}. Do not edit; run \`pnpm docs:reference\`. -->`,
    '',
    intro,
    '',
    // The engine version is added when the site is built (docs-site/scripts/sync.mjs),
    // so a release, which changes only version fields, does not change these pages.
    lang === 'en' ? '' : 'コードから取り込んだ説明文は英語のままです。',
    '',
    ...sections,
  ].join('\n').replace(/\n{3,}/g, '\n\n').trimEnd() + '\n';
}

const T = {
  en: {
    kind: { number: 'number', string: 'text', boolean: 'yes or no' },
    field: 'Field', kindH: 'Kind', meaning: 'Meaning', setting: 'Setting', required: 'Required', type: 'Type', description: 'Description',
    yes: 'yes', no: 'no', reason: 'Reason',
    display: 'For people and maps only; rules cannot use it.',
    probability: 'A number from 0 to 1.',
  },
  ja: {
    kind: { number: '数値', string: '文字列', boolean: 'はい・いいえ' },
    field: 'フィールド', kindH: '種類', meaning: '意味', setting: '設定', required: '必須', type: '型', description: '説明',
    yes: 'はい', no: 'いいえ', reason: '理由',
    display: '人と地図のための値です。ルールでは使えません。',
    probability: '0 から 1 までの数値です。',
  },
};

// ------------------------------------------------------------- fact types

/** The words for a field, with the fact's name shown as "name". */
function meaning(words, lang) {
  const fill = (s) => s.replaceAll('%', '*name*').replace(/\s+/g, ' ').trim();
  if (words === undefined) return '';
  if (Array.isArray(words)) return lang === 'en' ? `true: ${fill(words[0])}` : `true のとき: ${fill(words[0])}`;
  if (typeof words === 'string') return fill(words);
  return `${fill(words.subject)} (${words.unit})`;
}

/** A JSON Schema in a few words. */
function schemaType(s) {
  if (!s || typeof s !== 'object') return '';
  // A named schema by its name, a constant by its value.
  if (s.$ref) return code(s.$ref.split('/').pop());
  if (Object.hasOwn(s, 'const')) return JSON.stringify(s.const);
  if (s.enum) return s.enum.map((v) => JSON.stringify(v)).join(' | ');
  if (s.type === 'array') return schemaType(s.items) ? `${schemaType(s.items)}[]` : 'array';
  if (Array.isArray(s.type)) return s.type.join(' | ');
  return s.type ?? (s.oneOf || s.anyOf ? (s.oneOf ?? s.anyOf).map(schemaType).join(' | ') : '');
}

function factType(t, lang, answeredBy) {
  const w = T[lang];
  const words = t.words?.[lang]?.fields ?? {};
  const rows = Object.entries(t.fields).map(([name, f]) => [
    code(name),
    w.kind[f.kind],
    [meaning(words[name], lang), f.display && w.display, f.probability && w.probability].filter(Boolean).join(' '),
  ]);
  const out = [`### ${code(t.type)}`, '', sentence(t.description), ''];
  if (answeredBy) out.push(answeredBy, '');
  out.push(table([w.field, w.kindH, w.meaning], rows), '');
  const settings = Object.entries(t.settings ?? {});
  if (settings.length) {
    out.push(lang === 'en' ? 'Settings in a profile, besides `name`, `type` and `at`:' : 'プロファイルで `name`・`type`・`at` のほかに書ける設定です。', '');
    out.push(table([w.setting, w.type, w.required, w.description], settings.map(([k, s]) => [
      code(k), schemaType(s), (t.required ?? []).includes(k) ? w.yes : w.no, s.description,
    ])), '');
  }
  out.push(lang === 'en'
    ? `Missing as ${code(t.input.missing)} when the request has no value at \`at\` (${t.input.gloss.en}). A lookup gives up after ${t.timeoutMs / 1000} s.`
    : `\`at\` の位置に値がないときは ${code(t.input.missing)}(${t.input.gloss.ja})として欠けます。${t.timeoutMs / 1000} 秒で調べるのをやめます。`, '');
  return out;
}

async function factTypes(lang) {
  const facts = Object.keys(CATALOG).filter((n) => CATALOG[n].roles.includes('facts'));
  const defs = await loadDefinitions(facts.map((name) => ({ name })));
  const sections = [lang === 'en'
    ? 'In the tables, *name* stands for the name the profile gives the fact.'
    : '表の「意味」の列では、プロファイルでファクトに付けた名前を *name* と書いています。', ''];

  sections.push(lang === 'en' ? '## Shared fact types' : '## 共通のファクト型', '');
  sections.push(lang === 'en'
    ? 'Shared fact types (capabilities) are defined by the engine. Modules answer them, some only for their own layers.'
    : '共通のファクト型(ケイパビリティ)はエンジンが定義します。答えるのはモジュールで、自分のレイヤーにだけ答えるモジュールもあります。', '');
  for (const cap of Object.values(CAPABILITIES)) {
    const by = defs.flatMap((d) => (d.capabilities ?? []).filter((c) => c.type === cap.type).map((c) =>
      `${code(d.name)}${c.layers ? (lang === 'en' ? ` (layers ${list(c.layers)})` : `(レイヤー ${list(c.layers)})`) : ''}`));
    const answered = by.length
      ? (lang === 'en' ? `Answered by ${by.join(', ')}.` : `答えるモジュール: ${by.join('、')}`)
      : (lang === 'en' ? 'No module in this repository answers it.' : 'このリポジトリには答えるモジュールがありません。');
    sections.push(...factType(cap, lang, answered));
  }

  for (const d of defs.filter((d) => d.types?.length)) {
    sections.push(`## ${code(d.name)}`, '');
    sections.push(lang === 'en'
      ? `Fact types of the module ${code(d.name)}. Deployment settings it reads: ${list(d.settings)}.`
      : `モジュール ${code(d.name)} のファクト型です。このモジュールが読むデプロイの設定: ${list(d.settings)}`, '');
    for (const t of d.types) sections.push(...factType(t, lang));
  }

  sections.push(lang === 'en' ? '## Missing reasons' : '## 欠けた理由', '');
  sections.push(lang === 'en'
    ? 'A fact that has no value is *missing*: its field `missing` is true and `reason` says why. Rules can test both.'
    : '値のないファクトは「欠けた」ファクトです。フィールド `missing` が true になり、`reason` に理由が入ります。ルールではどちらも使えます。', '');
  const reasons = new Map(Object.entries(CORE_REASONS).map(([k, v]) => [k, { text: v, from: lang === 'en' ? 'any fact' : 'すべてのファクト' }]));
  for (const t of [...Object.values(CAPABILITIES), ...defs.flatMap((d) => d.types ?? [])]) {
    if (!reasons.has(t.input.missing)) reasons.set(t.input.missing, { text: t.input.gloss, from: [] });
    const r = reasons.get(t.input.missing);
    if (Array.isArray(r.from)) r.from.push(code(t.type));
  }
  for (const d of defs) {
    for (const [k, v] of Object.entries(d.reasons ?? {})) reasons.set(k, { text: v, from: code(d.name) });
  }
  sections.push(table([T[lang].reason, T[lang].meaning, lang === 'en' ? 'From' : '対象'],
    [...reasons].map(([k, r]) => [code(k), r.text[lang], Array.isArray(r.from) ? r.from.join(', ') : r.from])), '');

  return page(lang, lang === 'en'
    ? { order: 20, title: 'Fact types', description: 'Every fact type a profile can use, with its fields, settings and missing reasons.',
        intro: 'A *fact* is data that Pointsman looks up itself, for example whether a place is in a flood zone or how many files a pull request changes. The AI does not guess facts. A profile names each fact with a type from this page, and its rules read the fields of that type.' }
    : { order: 20, title: 'ファクトの型', description: 'プロファイルで使えるファクトの型と、そのフィールド、設定、欠けた理由の一覧です。',
        intro: 'ファクトとは、Pointsman 自身が調べるデータです。たとえば、ある場所が浸水想定区域に入るか、プルリクエストが変更したファイルの数などです。ファクトを AI が推測することはありません。プロファイルでは、このページの型を指定してファクトを定義し、ルールからその型のフィールドを読みます。' },
    sections);
}

// ------------------------------------------------------------- connectors

/** Where each connector's own page is. */
const CONNECTOR_DOCS = {
  '@pointsman/github': 'github-connector.md',
  '@pointsman/fiware': '../bridge/README.md',
};

async function connectors(lang) {
  const names = Object.keys(CATALOG).filter((n) => CATALOG[n].roles.includes('connector'));
  const defs = await loadDefinitions(names.map((name) => ({ name })));
  const where = {
    en: { engine: 'inside the Pointsman Worker', own: 'in its own Worker' },
    ja: { engine: 'Pointsman の Worker の中', own: '専用の Worker' },
  }[lang];
  const sections = [];
  for (const d of defs) {
    const c = d.connector;
    const doc = CONNECTOR_DOCS[d.name];
    sections.push(`## ${code(d.name)}`, '');
    sections.push(lang === 'en'
      ? `Connector ${code(c.id)} of the module ${code(d.name)}.${doc ? ` Setup and details: [its page](${rel(lang, doc)}).` : ''}`
      : `モジュール ${code(d.name)} のコネクター ${code(c.id)} です。${doc ? `設定方法と詳細は[専用のページ](${rel(lang, doc)})にあります。` : ''}`, '');
    sections.push(table(lang === 'en' ? ['What', 'Values'] : ['項目', '値'], [
      [lang === 'en' ? 'Runs' : '動かす場所', c.placements.map((p) => where[p]).join(lang === 'en' ? ', or ' : '、または')],
      [lang === 'en' ? 'Actions' : 'アクション', list(c.actions)],
      [lang === 'en' ? 'Settings' : '設定', list(c.settings)],
    ]), '');
  }
  return page(lang, lang === 'en'
    ? { order: 30, title: 'Connectors', description: 'Every connector, where it runs, its actions and its settings.',
        intro: `A *connector* connects Pointsman to another system: it brings cases in and carries the results out. [Connectors](${rel(lang, 'connectors.md')}) explains the idea.` }
    : { order: 30, title: 'コネクター', description: 'コネクターの一覧と、動かす場所、アクション、設定です。',
        intro: `コネクターは、Pointsman とほかのシステムをつなぎます。ケースを受け取って Pointsman に渡し、結果をそのシステムに返します。考え方は[コネクター](${rel(lang, 'connectors.md')})で説明しています。` },
    sections);
}

// ----------------------------------------------------------------- HTTP API

function httpApi(lang) {
  const api = parse(readFileSync(join(root, 'openapi.yaml'), 'utf8'));
  const resolve = (o) => {
    while (o?.$ref) o = o.$ref.slice(2).split('/').reduce((a, k) => a[k], api);
    return o;
  };
  const schemaName = (s) => (s?.$ref ? code(s.$ref.split('/').pop()) : schemaType(s));
  const w = T[lang];
  const sections = [];
  const methods = ['get', 'post', 'put', 'patch', 'delete'];
  for (const [path, item] of Object.entries(api.paths)) {
    for (const method of methods.filter((m) => item[m])) {
      const op = item[method];
      sections.push(`## ${method.toUpperCase()} ${path}`, '', `${op.summary}.`, '');
      if (op.description) sections.push(op.description.trim(), '');
      const params = (op.parameters ?? []).map(resolve);
      if (params.length) {
        sections.push(table([lang === 'en' ? 'Parameter' : 'パラメーター', lang === 'en' ? 'In' : '場所', w.required, w.description],
          params.map((p) => [code(p.name), p.in, p.required ? w.yes : w.no, p.description])), '');
      }
      const body = op.requestBody?.content?.['application/json']?.schema;
      if (body) sections.push(lang === 'en' ? `Request body: ${schemaName(body)} (JSON).` : `リクエストボディ: ${schemaName(body)}(JSON)`, '');
      sections.push(table([lang === 'en' ? 'Status' : 'ステータス', w.description, lang === 'en' ? 'Body' : 'ボディ'],
        Object.entries(op.responses).map(([status, r]) => {
          const res = resolve(r);
          const content = res.content && Object.entries(res.content)[0];
          return [status, res.description, content ? `${schemaName(content[1].schema)} (${content[0]})` : ''];
        })), '');
    }
  }
  sections.push(lang === 'en' ? '## Schemas' : '## スキーマ', '');
  for (const [name, schema] of Object.entries(api.components.schemas)) {
    sections.push(`### ${name}`, '');
    if (schema.description) sections.push(schema.description.trim(), '');
    const props = Object.entries(schema.properties ?? {});
    if (props.length) {
      sections.push(table([w.field, w.type, w.required, w.description], props.map(([k, p]) => [
        code(k), schemaName(p), (schema.required ?? []).includes(k) ? w.yes : w.no, resolve(p)?.description ?? p.description,
      ])), '');
    } else if (!schema.description) {
      sections.push(lang === 'en' ? `Type: ${schemaName(schema) || 'see openapi.yaml'}.` : `型: ${schemaName(schema) || 'openapi.yaml を参照'}`, '');
    }
  }
  return page(lang, lang === 'en'
    ? { order: 50, title: 'HTTP API', description: 'Every endpoint of the Pointsman HTTP API, with parameters, responses and schemas.',
        intro: `The Pointsman HTTP API. Every request needs an API token in the header \`Authorization: Bearer <token>\`. The full description, for tools that read OpenAPI, is [openapi.yaml](${rel(lang, '../openapi.yaml')}).` }
    : { order: 50, title: 'HTTP API', description: 'Pointsman の HTTP API のすべてのエンドポイントと、パラメーター、レスポンス、スキーマです。',
        intro: `Pointsman の HTTP API です。どのリクエストにも、ヘッダー \`Authorization: Bearer <token>\` で API トークンを付けます。OpenAPI を読むツール向けの完全な定義は [openapi.yaml](${rel(lang, '../openapi.yaml')}) にあります。` },
    sections);
}

// ---------------------------------------------------------------- MCP tools

async function mcpTools(lang) {
  const { TOOLS, PEOPLE_ONLY } = await import(pathToFileURL(join(root, 'src/mcp-tools.ts')).href);
  const w = T[lang];
  const sections = [];
  for (const [name, tool] of Object.entries(TOOLS)) {
    sections.push(`## ${code(name)}`, '', tool.description, '');
    if (PEOPLE_ONLY.has(name)) {
      sections.push(lang === 'en'
        ? 'Only for people logged in through OAuth, not for API tokens.'
        : 'OAuth でログインした人だけが使えます。API トークンでは使えません。', '');
    }
    const schema = z.toJSONSchema(z.object(tool.inputSchema));
    const props = Object.entries(schema.properties ?? {});
    sections.push(props.length
      ? table([lang === 'en' ? 'Argument' : '引数', w.type, w.required, w.description], props.map(([k, p]) => [
        code(k), schemaType(p) || 'object', (schema.required ?? []).includes(k) ? w.yes : w.no, p.description,
      ]))
      : (lang === 'en' ? 'No arguments.' : '引数はありません。'), '');
  }
  return page(lang, lang === 'en'
    ? { order: 85, title: 'MCP tools', description: 'The tools the Pointsman MCP server offers to AI agents, with their arguments.',
        intro: `Pointsman serves the Model Context Protocol (MCP) at \`/mcp\`, so AI agents can ask a decision profile instead of deciding on their own. [MCP server](${rel(lang, 'mcp.md')}) explains how to connect.` }
    : { order: 85, title: 'MCP ツール', description: 'Pointsman の MCP サーバーが AI エージェントに提供するツールと、その引数です。',
        intro: `Pointsman は \`/mcp\` で Model Context Protocol(MCP)を提供します。AI エージェントは自分で判断する代わりに、Pointsman のプロファイルに判定を頼めます。接続方法は [MCP サーバー](${rel(lang, 'mcp.md')})で説明しています。` },
    sections);
}

// ------------------------------------------------------------------- write

const PAGES = { 'fact-types': factTypes, connectors, 'http-api': httpApi, 'mcp-tools': mcpTools };

let stale = 0;
for (const [slug, make] of Object.entries(PAGES)) {
  for (const lang of ['en', 'ja']) {
    const file = join(root, 'docs', ...(lang === 'ja' ? ['ja'] : []), 'reference', `${slug}.md`);
    const text = await make(lang);
    const current = existsSync(file) ? readFileSync(file, 'utf8') : null;
    if (current === text) continue;
    if (check) {
      console.error(`out of date: ${file.slice(root.length + 1)}`);
      stale++;
      continue;
    }
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, text);
    console.log(`wrote ${file.slice(root.length + 1)}`);
  }
}
if (stale) {
  console.error(`\n${stale} generated page(s) out of date: run pnpm docs:reference and commit the result.`);
  process.exit(1);
}
