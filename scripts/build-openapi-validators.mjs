#!/usr/bin/env node
// Compile the response schemas in openapi.yaml to standalone validators
// (plain JS, no eval), so contract tests can run inside workerd.
//
// Usage: node scripts/build-openapi-validators.mjs [out-file]

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname } from 'node:path';
import Ajv2020 from 'ajv/dist/2020.js';
import standaloneCode from 'ajv/dist/standalone/index.js';
import { parse as parseYaml } from 'yaml';

const out = process.argv[2] ?? 'generated/openapi-validators.mjs';
const api = parseYaml(readFileSync('openapi.yaml', 'utf8'), { uniqueKeys: true });

const ajv = new Ajv2020({
  code: { source: true, esm: true },
  allErrors: true,
  // Formats (uuid, uri) are checked in the tests where they matter.
  validateFormats: false,
  // The wrapper below holds OpenAPI's "components" next to JSON Schema keywords.
  strict: false,
});
// One wrapper schema, so the "#/components/schemas/..." refs inside
// openapi.yaml resolve as they do in the OpenAPI document.
const base = 'https://pointsman.invalid/openapi';
const responses = {
  decision: { $ref: '#/components/schemas/Decision' },
  error: { $ref: '#/components/schemas/Error' },
  profileList: api.paths['/v1/profiles'].get.responses['200'].content['application/json'].schema,
};
ajv.addSchema({ $id: base, components: api.components, responses });
const ids = Object.fromEntries(Object.keys(responses).map((name) => [name, `${base}#/responses/${name}`]));

mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, standaloneCode(ajv, ids));
console.log(`Wrote ${Object.keys(ids).length} validators to ${out}`);

const types = `// Generated by scripts/build-openapi-validators.mjs.
export interface Validator {
  (data: unknown): boolean;
  errors?: { instancePath: string; message?: string }[] | null;
}
${Object.keys(ids).map((name) => `export declare const ${name}: Validator;`).join('\n')}
`;
writeFileSync(out.replace(/\.mjs$/, '.d.mts'), types);
