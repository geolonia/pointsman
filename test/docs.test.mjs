// The checks of the documentation site (docs-site/scripts, scripts/docs-reference.mjs):
// each runs and passes on this repository, and the language check fails on
// pages whose structure differs.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { mkdirSync, mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const run = (script, env = {}) => spawnSync(process.execPath, [join(root, script)], { cwd: root, encoding: 'utf8', env: { ...process.env, ...env } });

test('the generated reference pages match the code', () => {
  const r = spawnSync(process.execPath, [join(root, 'scripts/docs-reference.mjs'), '--check'], { cwd: root, encoding: 'utf8' });
  assert.equal(r.status, 0, r.stderr);
});

test('every page has an English and a Japanese version with the same structure', () => {
  const r = run('docs-site/scripts/check-languages.mjs');
  assert.equal(r.status, 0, r.stderr);
  assert.match(r.stdout, /pages in English and Japanese, same structure/);
});

test('the sync places every file and finds every linked file', () => {
  const r = run('docs-site/scripts/sync.mjs');
  assert.equal(r.status, 0, r.stderr);
  assert.match(r.stdout, /pages synced/);
});

function repo(t, files) {
  const dir = mkdtempSync(join(tmpdir(), 'pointsman-docs-'));
  t.after(() => rmSync(dir, { recursive: true, force: true }));
  for (const [file, text] of Object.entries(files)) {
    mkdirSync(dirname(join(dir, file)), { recursive: true });
    writeFileSync(join(dir, file), text);
  }
  return dir;
}

test('the language check fails on different headings, code blocks or a missing page', (t) => {
  const page = (body) => `---\ntitle: x\n---\n${body}\n`;
  const dir = repo(t, {
    'docs/reference/a.md': page('## One\n\n```sh\necho a\n```'),
    'docs/ja/reference/a.md': page('## 一\n\n### 二\n\n```sh\necho b\n```'),
    'docs/reference/b.md': page('text'),
  });
  const r = run('docs-site/scripts/check-languages.mjs', { POINTSMAN_DOCS_REPO: dir });
  assert.equal(r.status, 1);
  assert.match(r.stderr, /docs\/ja\/reference\/a\.md: headings differ/);
  assert.match(r.stderr, /docs\/ja\/reference\/a\.md: code block 1 differs/);
  assert.match(r.stderr, /docs\/reference\/b\.md: no Japanese version/);
});

test('the committed reference pages do not name the engine version, so a release does not change them', () => {
  const { version } = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
  for (const dir of ['docs/reference', 'docs/ja/reference']) {
    for (const file of readdirSync(join(root, dir))) {
      const text = readFileSync(join(root, dir, file), 'utf8');
      const named = new RegExp(`(?<![0-9.])${version.replaceAll('.', '\\.')}(?![0-9])`);
      if (text.includes('<!-- Generated by')) assert.ok(!named.test(text), `${dir}/${file} names version ${version}`);
    }
  }
});
