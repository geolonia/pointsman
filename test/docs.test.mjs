// In this file, not in page-markdown.test.mjs: test files run at the same time, and
// sync.mjs empties its output first, so only one file may run it.
test('every synced page converts, and keeps every line of every code block', () => {
  const sync = run('docs-site/scripts/sync.mjs');
  assert.equal(sync.status, 0, sync.stderr);
  const content = join(root, 'docs-site/src/content/docs');
  const files = readdirSync(content, { recursive: true }).map(String).filter((f) => /\.mdx?$/.test(f));
  assert.ok(files.length > 20);
  for (const file of files) {
    const text = readFileSync(join(content, file), 'utf8');
    const m = /^---\n([\s\S]*?)\n---\n/.exec(text);
    const data = parseYaml(m[1]);
    const source = text.slice(m[0].length);
    const out = pageMarkdown({ title: data.title, description: data.description, body: source, url: 'https://pointsman.net/docs/x/', file, mdx: file.endsWith('.mdx') });
    assert.doesNotMatch(withoutCode(out), /<svg|<details|<!--|\]\(\/docs\//, file);
    // The code blocks of the source, line by line, in the output in the same order.
    let fence = null;
    let indent = 0;
    let at = 0;
    for (const line of source.split('\n')) {
      const f = fence ? null : openFence(line);
      if (!fence && !f) continue;
      at = out.indexOf(`\n${line}\n`, at);
      assert.ok(at >= 0, `${file}: code line ${JSON.stringify(line)} is missing or changed`);
      // Every fence in the docs is in a list item at most, closed at the opening fence's indent.
      if (f) { fence = f; indent = /^ */.exec(line)[0].length; }
      else if (closesFence(line, fence, indent)) fence = null;
    }
  }
});

test('sitemap.xml lists every page of site/ with its other language, and robots.txt lists it', async () => {
  const { landingPaths, landingSitemap } = await import('../docs-site/scripts/landing-sitemap.mjs');
  const site = join(root, 'site');
  const paths = landingPaths(site);
  assert.ok(paths.includes('/') && paths.includes('/ja/'), 'the landing page in both languages');
  const xml = landingSitemap(site);
  for (const p of paths) assert.ok(xml.includes(`<loc>https://pointsman.net${p}</loc>`), `${p} is not in sitemap.xml`);
  assert.ok(xml.includes('hreflang="ja" href="https://pointsman.net/ja/"'));
  assert.ok(xml.includes('hreflang="x-default" href="https://pointsman.net/"'));
  assert.doesNotMatch(xml, /\/docs\//, 'the docs have their own sitemap');
  // The sitemap pairs the same pages as the pages' own hreflang links.
  for (const p of paths) {
    const head = readFileSync(join(site, p.slice(1), 'index.html'), 'utf8').split('</head>')[0];
    for (const [, lang, href] of head.matchAll(/<link rel="alternate" hreflang="([^"]+)" href="([^"]+)"/g)) {
      const entry = xml.split('\n').find((l) => l.includes(`<loc>https://pointsman.net${p}</loc>`));
      assert.ok(entry.includes(`hreflang="${lang}" href="${href}"`), `${p}: ${lang} ${href} is not in sitemap.xml`);
    }
  }
  const robots = readFileSync(join(site, 'robots.txt'), 'utf8');
  assert.match(robots, /^Sitemap: https:\/\/pointsman\.net\/sitemap\.xml$/m);
  assert.match(robots, /^Sitemap: https:\/\/pointsman\.net\/docs\/sitemap-index\.xml$/m);
});

